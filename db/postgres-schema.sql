CREATE TABLE IF NOT EXISTS battles (
  id text PRIMARY KEY, chat_id text NOT NULL, status text NOT NULL,
  created_at bigint NOT NULL, lobby_deadline bigint, countdown_at bigint,
  start_at bigint, lock_at bigint, end_at bigint, start_price double precision,
  end_price double precision, outcome text, message_id bigint,
  parent_id text UNIQUE, successor_id text, stake bigint NOT NULL DEFAULT 0,
  creator_user_id text
);
CREATE INDEX IF NOT EXISTS battles_chat ON battles(chat_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_battle_per_chat ON battles(chat_id)
  WHERE status IN ('lobby','countdown','live');

CREATE TABLE IF NOT EXISTS players (
  battle_id text NOT NULL REFERENCES battles(id) ON DELETE CASCADE,
  user_id text NOT NULL, name text NOT NULL, ready integer NOT NULL DEFAULT 0,
  prediction text, joined_at bigint NOT NULL DEFAULT 0,
  PRIMARY KEY(battle_id,user_id)
);
CREATE TABLE IF NOT EXISTS result_deliveries (
  battle_id text PRIMARY KEY REFERENCES battles(id) ON DELETE CASCADE,
  sent_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS stats (
  chat_id text NOT NULL, user_id text NOT NULL, name text NOT NULL,
  wins integer NOT NULL DEFAULT 0, losses integer NOT NULL DEFAULT 0,
  ties integer NOT NULL DEFAULT 0, streak integer NOT NULL DEFAULT 0,
  xp bigint NOT NULL DEFAULT 0, PRIMARY KEY(chat_id,user_id)
);
CREATE TABLE IF NOT EXISTS accounts (
  user_id text PRIMARY KEY, name text NOT NULL, balance bigint NOT NULL CHECK(balance >= 0),
  referral_code text NOT NULL UNIQUE, referred_by text, last_daily_date text NOT NULL,
  created_at bigint NOT NULL, last_seen_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS app_meta (key text PRIMARY KEY, value text NOT NULL);
CREATE TABLE IF NOT EXISTS pay_wallets (
  user_id text PRIMARY KEY REFERENCES accounts(user_id), address text NOT NULL UNIQUE,
  encrypted_secret text NOT NULL, privy_wallet_id text UNIQUE, created_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS paid_battles (
  battle_id text PRIMARY KEY REFERENCES battles(id), stake_minor bigint NOT NULL CHECK(stake_minor >= 100000),
  settlement_status text NOT NULL DEFAULT 'pending'
);
CREATE TABLE IF NOT EXISTS pay_faucets (
  user_id text PRIMARY KEY, amount_minor bigint NOT NULL, signature text NOT NULL UNIQUE,
  created_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS pay_transfers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, battle_id text NOT NULL,
  user_id text NOT NULL, kind text NOT NULL CHECK(kind IN ('stake','payout','refund','withdrawal','house')),
  amount_minor bigint NOT NULL CHECK(amount_minor > 0), signature text NOT NULL UNIQUE,
  created_at bigint NOT NULL, UNIQUE(battle_id,user_id,kind)
);
CREATE TABLE IF NOT EXISTS pay_intents (
  battle_id text NOT NULL, user_id text NOT NULL,
  kind text NOT NULL CHECK(kind IN ('stake','payout','refund','withdrawal','house')),
  amount_minor bigint NOT NULL CHECK(amount_minor > 0),
  state text NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','signed','confirmed','failed')),
  signature text UNIQUE, raw_transaction text, blockhash text,
  last_valid_block_height bigint, attempt integer NOT NULL DEFAULT 0,
  updated_at bigint NOT NULL, PRIMARY KEY(battle_id,user_id,kind)
);
CREATE TABLE IF NOT EXISTS pay_withdrawals (
  id text PRIMARY KEY, user_id text NOT NULL, recipient text NOT NULL,
  amount_minor bigint NOT NULL CHECK(amount_minor > 0), created_at bigint NOT NULL,
  approval_status text NOT NULL DEFAULT 'auto' CHECK(approval_status IN ('auto','pending','approved','rejected')),
  approved_at bigint, approved_by text
);
CREATE INDEX IF NOT EXISTS pay_withdrawals_user_date ON pay_withdrawals(user_id,created_at DESC);
CREATE TABLE IF NOT EXISTS processed_updates (update_id bigint PRIMARY KEY);
CREATE TABLE IF NOT EXISTS schema_migrations (
  version text PRIMARY KEY, applied_at bigint NOT NULL
);
